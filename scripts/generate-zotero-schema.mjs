import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { format } from "prettier";

// Download schema.json from zotero/zotero-schema separately and review its diff.
// This generator never fetches remote content or updates the snapshot on build.
const input = process.argv[2];
if (!input) throw new Error("Usage: pnpm exec node scripts/generate-zotero-schema.mjs /path/to/schema.json");
const bytes = await readFile(input);
const schema = JSON.parse(bytes.toString());
if (!Number.isInteger(schema.version) || !Array.isArray(schema.itemTypes))
  throw new Error("Invalid Zotero schema");
const data = Object.fromEntries(schema.itemTypes.map(({ itemType, fields, creatorTypes }) => [itemType, {
  fields: fields.map(({ field }) => field),
  baseFields: Object.fromEntries(fields.filter(({ baseField }) => baseField).map(({ field, baseField }) => [baseField, field])),
  primaryCreator: creatorTypes.find(({ primary }) => primary)?.creatorType ?? "author",
}]));
const source = `// Generated by scripts/generate-zotero-schema.mjs; do not edit by hand.
// Upstream: https://github.com/zotero/zotero-schema/blob/master/schema.json
// Schema version ${schema.version} (${schema.itemTypes.length} item types).
// Source SHA-256: ${createHash("sha256").update(bytes).digest("hex")}
// Data only: no runtime dependency on Zotero or a network connection.
export const ZOTERO_SCHEMA: Record<string, { fields: string[]; baseFields: Record<string, string>; primaryCreator: string }> = ${JSON.stringify(data)};
`;
await writeFile(new URL("../src/zotero-schema-data.ts", import.meta.url), await format(source, { parser: "typescript", printWidth: 80 }));
